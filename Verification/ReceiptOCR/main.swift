var failures = 0

// 位置つきのOCR要素を短く作る補助関数です。
func item(_ text: String, _ x: CGFloat = 0.1, _ y: CGFloat = 0.2, _ width: CGFloat = 0.3, _ height: CGFloat = 0.04) -> ReceiptTextParser.Element {
    // 渡された文字列と正規化された画像座標を一つの要素にします。
    return ReceiptTextParser.Element(text: text, frame: CGRect(x: x, y: y, width: width, height: height))
// OCR要素を作る補助関数の定義を閉じます。
}

// 条件式が期待どおりなら成功、違えば失敗として記録します。
func verify(_ name: String, _ condition: Bool) {
    // 条件が成立したテスト名を成功として表示します。
    if condition {
        // 成功した項目を人が確認できる形で表示します。
        print("PASS: \(name)")
    // 条件が成立しない場合の失敗処理を始めます。
    } else {
        // 失敗数を一つ増やします。
        failures += 1
        // 失敗した項目名を表示します。
        print("FAIL: \(name)")
    // 成功と失敗の分岐を閉じます。
    }
// テスト結果を記録する補助関数の定義を閉じます。
}

