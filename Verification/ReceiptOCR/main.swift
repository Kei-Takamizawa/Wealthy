// 入力配列順ではなく画像上の位置で並んだことを確認します。
verify("入力順と異なる行・列のソート", orderedRowText == ["左 右", "下"])

// 互いに少しずつ重なるが最初と最後は同じ行でない3つの領域を作ります。
